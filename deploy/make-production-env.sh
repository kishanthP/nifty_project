#!/usr/bin/env bash
# Run on YOUR PC (Git Bash), in the project folder:
#     bash deploy/make-production-env.sh niftyalerts.duckdns.org
#
# Writes .env.production: your Angel One and Firebase values from .env, production
# settings for the given address, and a new random database password.
# Copy it to the server as ".env" (see deploy/DEPLOY.md). It is git-ignored.
set -euo pipefail

domain="${1:-}"
if [[ -z "$domain" || "$domain" == http* || "$domain" == */* ]]; then
    echo "Usage: bash deploy/make-production-env.sh your-name.duckdns.org" >&2
    echo "(just the address: no https://, no slashes)" >&2
    exit 1
fi

cd "$(dirname "$0")/.."
if [[ ! -f .env ]]; then
    echo "No .env here. Run this in the project folder on your PC." >&2
    exit 1
fi

# Value of KEY in .env (empty if missing).
get() { grep -E "^$1=" .env | head -n 1 | cut -d= -f2- | tr -d '\r' || true; }

missing=()
for key in ANGELONE_API_KEY ANGELONE_CLIENT_CODE ANGELONE_PIN ANGELONE_TOTP_SECRET \
    VITE_FIREBASE_API_KEY VITE_FIREBASE_PROJECT_ID VITE_FIREBASE_APP_ID VITE_FIREBASE_VAPID_KEY; do
    [[ -n "$(get "$key")" ]] || missing+=("$key")
done
if (( ${#missing[@]} )); then
    echo "These are empty in .env, fill them first: ${missing[*]}" >&2
    exit 1
fi

# Letters and digits only, so it is safe inside the database URL.
password="$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"

if [[ -f .env.production ]]; then
    cp .env.production .env.production.bak
    echo "Kept the previous file as .env.production.bak"
fi

cat > .env.production <<EOF
# Production settings for https://$domain
# Generated by deploy/make-production-env.sh. Keep this file private.

DOMAIN=$domain
ENVIRONMENT=production
LOG_LEVEL=INFO
FRONTEND_URL=https://$domain
CORS_ORIGINS=https://$domain

# ---------- PostgreSQL (private to the server) ----------
POSTGRES_USER=share_market
POSTGRES_PASSWORD=$password
POSTGRES_DB=share_market
DATABASE_URL=postgresql+asyncpg://share_market:$password@postgres:5432/share_market

# ---------- Redis (private to the server) ----------
REDIS_URL=redis://redis:6379/0

# ---------- Market data ----------
MARKET_DATA_PROVIDER=angelone
FALLBACK_PROVIDER=yahoo
FALLBACK_AFTER_SECONDS=60
ANGELONE_API_KEY=$(get ANGELONE_API_KEY)
ANGELONE_CLIENT_CODE=$(get ANGELONE_CLIENT_CODE)
ANGELONE_PIN=$(get ANGELONE_PIN)
ANGELONE_TOTP_SECRET=$(get ANGELONE_TOTP_SECRET)

# ---------- Firebase ----------
FIREBASE_CREDENTIALS_FILE=/app/secrets/firebase-service-account.json
AUTH_DEV_MODE=false

# ---------- Web app (public values, built into the JavaScript) ----------
VITE_API_URL=https://$domain
VITE_AUTH_DEV_MODE=false
VITE_FIREBASE_API_KEY=$(get VITE_FIREBASE_API_KEY)
VITE_FIREBASE_AUTH_DOMAIN=$(get VITE_FIREBASE_AUTH_DOMAIN)
VITE_FIREBASE_PROJECT_ID=$(get VITE_FIREBASE_PROJECT_ID)
VITE_FIREBASE_STORAGE_BUCKET=$(get VITE_FIREBASE_STORAGE_BUCKET)
VITE_FIREBASE_MESSAGING_SENDER_ID=$(get VITE_FIREBASE_MESSAGING_SENDER_ID)
VITE_FIREBASE_APP_ID=$(get VITE_FIREBASE_APP_ID)
VITE_FIREBASE_VAPID_KEY=$(get VITE_FIREBASE_VAPID_KEY)
EOF

echo "Wrote .env.production for https://$domain"
echo "Next: copy it to the server as .env (deploy/DEPLOY.md, step 7)."
